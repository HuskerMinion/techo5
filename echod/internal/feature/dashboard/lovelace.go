// A dashboard of Home Assistant's own, drawn card by card. A sections view's sections, and a masonry
// view's cards, become the page's sections, laid out in columns the way Home Assistant lays them out.
// The cards people use most are drawn in the house's theme: tiles, cards of rows, headings, text,
// graphs, gauges and pictures. Stacks and grids are opened into the section they are in, and a card
// the device does not know is a tile that says what it is, so nothing silently goes missing.
//
// A dashboard Home Assistant generates for itself (the default Overview, until somebody takes it
// over) has no cards to read, and is drawn as the Rooms dashboard, which is what it would show.

type lovelaceSource struct {
	dashboard string // url_path; "lovelace" for the default
	view      string // a view's path or index; empty for the first

	sects    [][]node
	fallback *roomsSource
}

func newLovelace(path string) *lovelaceSource {
	dash, view, _ := strings.Cut(strings.Trim(path, "/"), "/")
	return &lovelaceSource{dashboard: dash, view: view}
}

func (l *lovelaceSource) load(ctx context.Context, live *hass.Live) (needs, error) {
	// Loaded again on every connection, and after an edit: what was read last time goes.
	l.sects, l.fallback = nil, nil
	cmd := map[string]any{"type": "lovelace/config"}
	if l.dashboard != "" && l.dashboard != "lovelace" {
		cmd["url_path"] = l.dashboard
	}
	rawCfg, err := live.Call(ctx, cmd)
	if err != nil {
		return needs{}, fmt.Errorf("Home Assistant would not give this dashboard.")
	}
	var cfg struct {
		Views []raw `json:"views"`
	}
	if err := json.Unmarshal(rawCfg, &cfg); err != nil {
		return needs{}, err
	}
	if len(cfg.Views) == 0 {
		// Generated by Home Assistant: its areas are what it would show.
		l.fallback = &roomsSource{}
		return l.fallback.load(ctx, live)
	}
	view := cfg.Views[0]
	for i, v := range cfg.Views {
		if str(v, "path") == l.view || strconv.Itoa(i) == l.view {
			view = v
		}
	}

	c := &compiler{seen: map[string]bool{}, need: needs{graphs: map[string]int{}}}
	if b := c.badges(view["badges"]); b != nil {
		l.sects = append(l.sects, []node{b})
	}
	if sections, ok := view["sections"].([]any); ok {
		for _, s := range sections {
			if sm, ok := s.(raw); ok {
				nodes := c.cards(sm["cards"])
				if len(nodes) == 0 {
					continue
				}
				if vis := c.conditions(sm["visibility"]); len(vis) > 0 {
					nodes = []node{condNode{conds: vis, child: group(nodes)}}
				}
				l.sects = append(l.sects, nodes)
			}
		}
	}
	// A masonry view: each card is a section of its own, and they flow into the columns.
	list, _ := view["cards"].([]any)
	for _, item := range list {
		if card, ok := item.(raw); ok {
			if n := c.card(card); n != nil {
				l.sects = append(l.sects, []node{n})
			}
		}
	}
	return c.need, nil
}

func (l *lovelaceSource) sections(lk look) []Section {
	if l.fallback != nil {
		return l.fallback.sections(lk)
	}
	var out []Section
	for _, nodes := range l.sects {
		var blocks []Block
		for _, n := range nodes {
			blocks = append(blocks, n.blocks(lk)...)
		}
		// Tiles one after another make one grid, however many cards they came from: a section of
		// tile cards is one grid in Home Assistant too.
		var merged []Block
		for _, b := range blocks {
			if n := len(merged); n > 0 && onlyTiles(b) && onlyTiles(merged[n-1]) {
				merged[n-1].Tiles = append(merged[n-1].Tiles, b.Tiles...)
				continue
			}
			merged = append(merged, b)
		}
		if len(merged) > 0 {
			out = append(out, Section{Blocks: merged})
		}
	}
	return out
}

func onlyTiles(b Block) bool {
	return len(b.Tiles) > 0 && b.Heading == "" && b.Title == "" && len(b.Rows) == 0 && len(b.Text) == 0 &&
		b.Graph == nil && b.Gauge == nil && b.Picture == nil
}

// node is a compiled card: what it draws from what has arrived.
type node interface {
	blocks(l look) []Block
}

type compiler struct {
	seen map[string]bool
	need needs
}

func (c *compiler) follow(entity string) {
	if entity != "" && !c.seen[entity] {
		c.seen[entity] = true
		c.need.entities = append(c.need.entities, entity)
	}
}

// render registers text for Home Assistant to render if it is a template, and says how to read it.
func (c *compiler) render(text, entity string) textRef {
	if !strings.Contains(text, "{{") && !strings.Contains(text, "{%") {
		return textRef{plain: text}
	}
	id := len(c.need.templates) + 1
	vars := map[string]any{}
	if entity != "" {
		vars["entity"] = entity
	}
	c.need.templates = append(c.need.templates, template{id: id, text: text, vars: vars})
	return textRef{template: id}
}

// textRef is words on the page: as written, or a template's latest rendering.
type textRef struct {
	plain    string
	template int
}

func (t textRef) get(rendered map[int]string) string {
	if t.template != 0 {
		return strings.TrimSpace(rendered[t.template])
	}
	return t.plain
}

func (c *compiler) cards(v any) []node {
	list, _ := v.([]any)
	var out []node
	for _, item := range list {
		if card, ok := item.(raw); ok {
			if n := c.card(card); n != nil {
				out = append(out, n)
			}
		}
	}
	return out
}

