// jpUI returns a translated settings string when Japanese is selected.
// The original English string is kept as a safe fallback for all other languages.
func jpUI(english string) string {
	if config.Get().Screen.Language != "ja" {
		return english
	}
	if translated, ok := japaneseUI[english]; ok {
		return translated
	}
	return english
}

