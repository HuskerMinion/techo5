package locale

// Text returns a UI message by a stable, language-independent key. Missing or
// empty translations fall back to English; unknown keys are returned verbatim.
// Add a language to uiTranslations without changing callers or drawing code.
func Text(lang, key string) string {
	english, ok := uiEnglish[key]
	if !ok {
		return key
	}
	return translated(lang, key, uiTranslations, english)
}

// translated is the common fallback policy for UI, date phrases and updates.
func translated(lang, key string, catalog map[string]map[string]string, english string) string {
	if s := catalog[lang][key]; s != "" {
		return s
	}
	return english
}

